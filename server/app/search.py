class SearchService:
    def __init__(self, settings: Settings, upstream: AnthropicUpstream) -> None:
        self.settings = settings
        self.upstream = upstream
        self._client: httpx.AsyncClient | None = None

    async def start(self) -> None:
        timeout = httpx.Timeout(connect=8.0, read=self.settings.search.timeout, write=30.0, pool=None)
        self._client = httpx.AsyncClient(
            timeout=timeout,
            follow_redirects=True,
            headers={"User-Agent": self.settings.search.user_agent},
        )

    async def close(self) -> None:
        if self._client is not None:
            await self._client.aclose()
            self._client = None

    @property
    def client(self) -> httpx.AsyncClient:
        if self._client is None:
            raise RuntimeError("search client is not started")
        return self._client

    # -- configuration -----------------------------------------------------
    def _config(
        self,
        override: dict[str, Any] | None,
        official_api_key: str | None = None,
    ) -> tuple[str, str, SearchConfig]:
        """Resolve ``(mode, provider, config)`` with per-user overrides.

        ``official_api_key`` is the *effective* official key for this request
        (user credential first, env fallback) — the caller resolves it so that
        every user's retrieval uses their own key.
        """
        config = SearchConfig(**{f.name: getattr(self.settings.search, f.name) for f in self.settings.search.__dataclass_fields__.values()})
        mode = self.settings.search.mode
        provider = self.settings.search.provider
        if isinstance(official_api_key, str) and official_api_key:
            config.official_api_key = official_api_key
        if isinstance(override, dict):
            user_mode = override.get("mode")
            if isinstance(user_mode, str) and user_mode.strip().lower() in ("dgx", "official", "off"):
                mode = user_mode.strip().lower()
            user_provider = override.get("provider")
            if isinstance(user_provider, str) and user_provider.strip().lower() in (
                "deepseek",
                "brave",
                "tavily",
                "searxng",
                "google_cse",
                "none",
            ):
                provider = user_provider.strip().lower()
            base = override.get("base_url")
            key = override.get("api_key")
            user_base = base.strip() if isinstance(base, str) and base.strip() else ""
            user_key = key.strip() if isinstance(key, str) and key.strip() else ""
            if user_base:
                config.provider_base_url = user_base
                # SECURITY: never forward the server's search credential to a
                # host chosen by a normal user.  A custom endpoint must bring its
                # own key; otherwise no Authorization is sent at all.
                if not user_key:
                    config.provider_api_key = ""
            if user_key:
                config.provider_api_key = user_key
            limit = override.get("max_results")
            if isinstance(limit, int) and 1 <= limit <= 20:
                config.max_results = limit
        return mode, provider, config

    def _provider(self, provider: str, config: SearchConfig) -> _Provider | None:
        if provider == "deepseek":
            return None  # handled by official retrieval
        factory = _PROVIDERS.get(provider)
        if factory is None:
            return None
        instance = factory(config, self.client)
        return instance if instance.enabled else None

    def available(
        self,
        override: dict[str, Any] | None = None,
        official_api_key: str | None = None,
    ) -> tuple[bool, str]:
        mode, provider, config = self._config(override, official_api_key)
        if mode == "off":
            return False, "off"
        if mode == "official":
            if config.official_api_key:
                return True, "official"
            return False, "unavailable"
        if provider == "deepseek":
            return (
                bool(config.official_api_key),
                "official_retrieval" if config.official_api_key else "unavailable",
            )
        instance = self._provider(provider, config)
        return (instance is not None, provider if instance is not None else "unavailable")

    # -- public API --------------------------------------------------------
    async def plan(
        self,
        *,
        query: str,
        urls: list[str],
        want_search: bool,
        want_read_url: bool,
        user_settings: dict[str, Any] | None = None,
        official_api_key: str | None = None,
    ) -> SearchPlan:
        mode, provider, config = self._config(user_settings, official_api_key)
        plan = SearchPlan()
        if mode == "off":
            plan.notice = "off"
            return plan

        tasks: list[asyncio.Task[Any]] = []
        if want_search:
            tasks.append(asyncio.create_task(self._web_search(query, provider, config)))
        if want_read_url and urls:
            tasks.append(asyncio.create_task(self._read_urls(urls, config)))
        if not tasks:
            plan.notice = "off"
            return plan

        results = await asyncio.gather(*tasks, return_exceptions=True)
        if want_search:
            search_result = results[0]
            if isinstance(search_result, Exception):
                logger.warning("web search failed: %s", search_result)
                plan.notice = "error"
            else:
                blocks, sources, tool_queries = search_result
                plan.blocks.extend(blocks)
                plan.sources = sources
                plan.web_search_requests = 1 if blocks else 0
                plan.notice = search_result_note(provider)
                if not blocks:
                    plan.notice = "no_results"
            if want_read_url and urls:
                read_result = results[1]
            else:
                read_result = None
        else:
            read_result = results[0]
            plan.notice = search_result_note(provider) if want_search else "off"

        if isinstance(read_result, Exception):
            logger.warning("read_url failed: %s", read_result)
        elif read_result:
            page_blocks, pages, fetches = read_result
            plan.blocks.extend(page_blocks)
            plan.pages = pages
            plan.web_fetch_requests += fetches
            if plan.notice in ("off", "unavailable"):
                plan.notice = "read_url"

        plan.context_text = self._build_context(plan)
        return plan

    # -- web search --------------------------------------------------------
    async def _web_search(
        self, query: str, provider: str, config: SearchConfig
    ) -> tuple[list[dict[str, Any]], list[Source], list[str]]:
        if not query.strip():
            return [], [], []
        if provider == "deepseek":
            return await self._official_retrieval(query, config)
        instance = self._provider(provider, config)
        if instance is None:
            raise SearchProviderError(f"search provider '{provider}' is not configured")
        sources = (await instance.search(query, config.max_results))[: config.max_results]
        logger.info(
            "search provider=%s query=%r -> %d sources",
            provider,
            query[:200],
            len(sources),
        )
        if not sources:
            return [], [], [query]
        tool_block, result_block = synth_search_blocks([query], sources, sequence=0)
        return [tool_block, result_block], sources, [query]

    async def _official_retrieval(
        self, query: str, config: SearchConfig
    ) -> tuple[list[dict[str, Any]], list[Source], list[str]]:
        """Ask the official endpoint for results only, then abort the stream."""
        api_key = config.official_api_key
        if not api_key:
            raise SearchProviderError("DEEPSEEK_API_KEY 未配置，无法检索")
        payload = build_retrieval_payload(
            query, model=config.official_model or "deepseek-flash"
        )
        logger.info(
            "search retrieval: model=%s time_context=%r query=%r",
            payload["model"],
            retrieval_time_context()[:60],
            query[:200],
        )
        tool_blocks: list[dict[str, Any]] = []
        sources: list[Source] = []
        queries: list[str] = []

        async def consume() -> None:
            agen = self.upstream.iter_events(payload, api_key)
            try:
                async for _event, data in agen:
                    kind = data.get("type")
                    if kind == "content_block_start":
                        block = data.get("content_block") or {}
                        if block.get("type") == "server_tool_use" and block.get("name") == "deepseek_web_search":
                            tool_blocks.append(block)
                            raw_input = block.get("input")
                            if isinstance(raw_input, dict):
                                for value in raw_input.get("queries") or []:
                                    if isinstance(value, str):
                                        queries.append(value)
                        elif block.get("type") == "web_search_tool_result":
                            tool_blocks.append(block)
                            for item in block.get("content") or []:
                                if isinstance(item, dict) and item.get("type") == "web_search_result":
                                    url = item.get("url")
                                    if not isinstance(url, str):
                                        continue
                                    sources.append(
                                        Source(
                                            title=str(item.get("title") or url),
                                            url=url,
                                            snippet=str(item.get("snippet") or ""),
                                            site_name=item.get("site_name"),
                                            site_icon=item.get("site_icon"),
                                            page_age=item.get("page_age"),
                                            encrypted_content=str(item.get("encrypted_content") or ""),
                                        )
                                    )
                            return  # got what we need: abort the upstream stream
                        elif block.get("type") == "text":
                            return  # no search happened
            finally:
                await agen.aclose()

        await asyncio.wait_for(consume(), timeout=config.timeout)
        if queries:
            logger.info(
                "search queries generated by official model: %s",
                truncate(json.dumps([q[:200] for q in queries], ensure_ascii=False), 800),
            )
        logger.info("search retrieval returned %d sources", len(sources))
        if not sources:
            return [], [], queries or [query]
        return list(tool_blocks), sources[: max(config.max_results, 11)], queries or [query]

    # -- read_url ----------------------------------------------------------
    async def _read_urls(
        self, urls: list[str], config: SearchConfig
    ) -> tuple[list[dict[str, Any]], list[FetchedPage], int]:
        pages: list[FetchedPage] = []
        limit = max(1, self.settings.search.max_pages_per_turn)
        for url in urls[:limit]:
            try:
                page = await asyncio.wait_for(self._fetch_page(url, config), timeout=config.fetch_timeout + 2)
            except asyncio.TimeoutError:
                page = FetchedPage(url=url, error="url_not_accessible")
            except Exception as exc:  # noqa: BLE001 - any fetch failure is reported to the client
                logger.info("read_url %s failed: %s", url, exc)
                page = FetchedPage(url=url, error="url_not_accessible")
            pages.append(page)

        blocks: list[dict[str, Any]] = []
        for index, page in enumerate(pages):
            tool_id = f"srvtoolu_rl_{index:02d}_{secrets.token_hex(16)}"
            blocks.append(
                {
                    "type": "server_tool_use",
                    "id": tool_id,
                    "name": "deepseek_read_url",
                    "input": {"action": "open_page", "url": page.url},
                    "caller": {"type": "direct"},
                    "kind": "read_link",
                }
            )
            if page.error:
                content: dict[str, Any] = {
                    "type": "web_fetch_tool_result_error",
                    "error_code": page.error,
                }
            else:
                content = {
                    "type": "web_fetch_result",
                    "url": page.url,
                    "content": {
                        "type": "document",
                        "source": {
                            "type": "text",
                            "media_type": "text/plain",
                            "data": truncate(page.text, config.fetch_max_chars),
                        },
                        "title": page.title,
                    },
                    "published_at": page.published_at,
                }
            blocks.append(
                {
                    "type": "web_fetch_tool_result",
                    "tool_use_id": tool_id,
                    "content": content,
                    "kind": "read_link",
                }
            )
        fetches = sum(1 for page in pages if not page.error)
        return blocks, pages, fetches

    async def _fetch_page(self, url: str, config: SearchConfig) -> FetchedPage:
        response = await self.client.get(url, timeout=config.fetch_timeout)
        if response.status_code >= 400:
            return FetchedPage(url=url, error="url_not_accessible")
        content_type = (response.headers.get("content-type") or "").lower()
        raw = response.content[:MAX_FETCH_BYTES]
        if "html" in content_type or b"<html" in raw[:2048].lower():
            text, title, published = html_to_text(raw.decode("utf-8", "replace"))
        elif "json" in content_type or "text/" in content_type or not content_type:
            text = raw.decode("utf-8", "replace")
            title = None
            published = None
        else:
            return FetchedPage(url=url, error="url_not_accessible")
        if not text.strip():
            return FetchedPage(url=url, error="url_not_accessible")
        return FetchedPage(
            url=url,
            title=title,
            text=truncate(text, config.fetch_max_chars),
            published_at=published,
        )

    # -- prompt context ----------------------------------------------------
    def _build_context(self, plan: SearchPlan) -> str:
        parts: list[str] = []
        if plan.sources:
            lines = ["【本轮联网检索结果】"]
            for index, source in enumerate(plan.sources, start=1):
                snippet = truncate(re.sub(r"\s+", " ", source.snippet or ""), 400)
                lines.append(f"[{index}] {source.title}\nURL: {source.url}")
                if snippet:
                    lines.append(f"摘要: {snippet}")
            lines.append("")
            lines.append(
                "请结合上述检索结果回答，并在引用处用 [序号] 标注来源（例如 [1]、[2]）。"
                "如果检索结果与问题无关，可以忽略它们。"
            )
            parts.append("\n".join(lines))
        if plan.pages:
            lines = ["【本轮读取的网页正文】"]
            for page in plan.pages:
                if page.error:
                    lines.append(f"- {page.url}（读取失败：{page.error}）")
                    continue
                lines.append(f"URL: {page.url}")
                if page.title:
                    lines.append(f"标题: {page.title}")
                lines.append(page.text)
                lines.append("")
            parts.append("\n".join(lines))
        return "\n\n".join(part for part in parts if part.strip())


