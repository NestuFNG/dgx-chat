class SearchProviderError(Exception):
    pass


class _Provider:
    name = "none"

    def __init__(self, config: SearchConfig, http: httpx.AsyncClient) -> None:
        self.config = config
        self.http = http

    async def search(self, query: str, limit: int) -> list[Source]:  # pragma: no cover - abstract
        raise NotImplementedError

    @property
    def enabled(self) -> bool:
        return False


class BraveProvider(_Provider):
    name = "brave"

    @property
    def enabled(self) -> bool:
        return bool(self.config.provider_api_key and self.config.provider_base_url)

    async def search(self, query: str, limit: int) -> list[Source]:
        response = await self.http.get(
            self.config.provider_base_url,
            params={"q": query, "count": limit},
            headers={"X-Subscription-Token": self.config.provider_api_key, "Accept": "application/json"},
        )
        if response.status_code != 200:
            raise SearchProviderError(f"brave HTTP {response.status_code}")
        data = response.json()
        results: list[Source] = []
        for item in (data.get("web") or {}).get("results") or []:
            url = item.get("url")
            if not isinstance(url, str):
                continue
            results.append(
                Source(
                    title=str(item.get("title") or url),
                    url=url,
                    snippet=str(item.get("description") or ""),
                    site_name=item.get("profile") or urlparse(url).hostname,
                    site_icon=site_icon_for(url),
                    page_age=item.get("age"),
                )
            )
        return results[:limit]


class TavilyProvider(_Provider):
    name = "tavily"

    @property
    def enabled(self) -> bool:
        return bool(self.config.provider_api_key)

    async def search(self, query: str, limit: int) -> list[Source]:
        response = await self.http.post(
            self.config.provider_base_url or "https://api.tavily.com/search",
            json={
                "api_key": self.config.provider_api_key,
                "query": query,
                "max_results": limit,
                "include_answer": False,
            },
        )
        if response.status_code != 200:
            raise SearchProviderError(f"tavily HTTP {response.status_code}")
        data = response.json()
        results: list[Source] = []
        for item in data.get("results") or []:
            url = item.get("url")
            if not isinstance(url, str):
                continue
            results.append(
                Source(
                    title=str(item.get("title") or url),
                    url=url,
                    snippet=str(item.get("content") or ""),
                    site_name=urlparse(url).hostname,
                    site_icon=site_icon_for(url),
                )
            )
        return results[:limit]


class SearxngProvider(_Provider):
    name = "searxng"

    @property
    def enabled(self) -> bool:
        return bool(self.config.provider_base_url)

    async def search(self, query: str, limit: int) -> list[Source]:
        response = await self.http.get(
            self.config.provider_base_url.rstrip("/") + "/search",
            params={"q": query, "format": "json", "language": "zh-CN"},
        )
        if response.status_code != 200:
            raise SearchProviderError(f"searxng HTTP {response.status_code}")
        data = response.json()
        results: list[Source] = []
        for item in data.get("results") or []:
            url = item.get("url")
            if not isinstance(url, str):
                continue
            published = item.get("publishedDate")
            results.append(
                Source(
                    title=str(item.get("title") or url),
                    url=url,
                    snippet=str(item.get("content") or ""),
                    site_name=urlparse(url).hostname,
                    site_icon=site_icon_for(url),
                    page_age=str(published) if published else None,
                )
            )
        return results[:limit]


class GoogleCseProvider(_Provider):
    name = "google_cse"

    @property
    def enabled(self) -> bool:
        return bool(self.config.provider_api_key and self.config.provider_base_url)

    async def search(self, query: str, limit: int) -> list[Source]:
        response = await self.http.get(
            self.config.provider_base_url,
            params={"q": query, "num": min(limit, 10), "key": self.config.provider_api_key},
        )
        if response.status_code != 200:
            raise SearchProviderError(f"google_cse HTTP {response.status_code}")
        data = response.json()
        results: list[Source] = []
        for item in data.get("items") or []:
            url = item.get("link")
            if not isinstance(url, str):
                continue
            results.append(
                Source(
                    title=str(item.get("title") or url),
                    url=url,
                    snippet=str(item.get("snippet") or ""),
                    site_name=urlparse(url).hostname,
                    site_icon=site_icon_for(url),
                )
            )
        return results[:limit]


