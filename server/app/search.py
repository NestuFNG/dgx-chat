"""联网搜索 / 链接阅读 (SPEC §3.5).

The default mode is ``dgx``: retrieval happens here, the answer text is always
generated by the local DGX gateway.  The DeepSeek official key is used only to
obtain retrieval results (search) — the request is aborted as soon as the
``web_search_tool_result`` block arrives, exactly as measured in
``FACTS_UPSTREAM.md`` §B2.

Pluggable providers (brave / tavily / searxng / google_cse) synthesise the same
block shapes so the client cannot tell the difference.

``SEARCH_MODE=official`` (opt-in) relays the whole turn to the official
Anthropic endpoint; that path lives in :mod:`app.anthropic_compat`.
"""

