#!/bin/sh
# =============================================================================
# DGX Chat — one-command deployment.
#
#   ./scripts/quickstart.sh              build + start, wait for health
#   ./scripts/quickstart.sh --api-only   skip building the web UI
#   ./scripts/quickstart.sh --rebuild-web  force a front-end rebuild (upgrades)
#   ./scripts/quickstart.sh --status     show status and health, change nothing
#
# Safe to re-run: an existing .env and the data volume are never overwritten.
# The web UI is rebuilt automatically when app/ sources are newer than web/,
# so `git pull && ./scripts/quickstart.sh` upgrades both halves.
# Requirements: docker + the docker compose plugin (and curl or wget to wait).
# =============================================================================
set -eu

REPO_DIR=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$REPO_DIR"

COMPOSE_FILE="server/docker-compose.yml"
ENV_FILE="server/.env"
PORT=8439   # published port from server/docker-compose.yml
API_ONLY=0
STATUS_ONLY=0
REBUILD_WEB=0

for arg in "$@"; do
    case "$arg" in
        --api-only) API_ONLY=1 ;;
        --status) STATUS_ONLY=1 ;;
        --rebuild-web) REBUILD_WEB=1 ;;
        -h|--help) sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "quickstart: unknown argument: $arg" >&2; exit 2 ;;
    esac
done

say()  { printf '%s\n' "$*"; }
step() { printf '\n==> %s\n' "$*"; }
warn() { printf 'warning: %s\n' "$*" >&2; }
die()  { printf 'error: %s\n' "$*" >&2; exit 1; }

# --- 1. prerequisites --------------------------------------------------------
step "Checking docker"
command -v docker >/dev/null 2>&1 || die "docker is not installed.
  Install Docker Engine (or Docker Desktop), then re-run this script."
docker compose version >/dev/null 2>&1 || die "the 'docker compose' plugin is missing.
  Install the Compose v2 plugin (docker-compose-plugin), then re-run."
[ -f "$COMPOSE_FILE" ] || die "missing $COMPOSE_FILE — run this script from a clone of the repository."

# --- 2. .env -----------------------------------------------------------------
gen_hex() {
    # $1 = number of bytes. Prefer /dev/urandom; fall back to openssl or python.
    if [ -r /dev/urandom ] && command -v od >/dev/null 2>&1; then
        od -An -N"$1" -tx1 /dev/urandom | tr -d ' \n'
    elif command -v openssl >/dev/null 2>&1; then
        openssl rand -hex "$1"
    elif command -v python3 >/dev/null 2>&1; then
        python3 -c "import secrets,sys; sys.stdout.write(secrets.token_hex($1))"
    else
        die "cannot generate random values (need /dev/urandom, openssl or python3)"
    fi
}

if [ "$STATUS_ONLY" -eq 0 ]; then
    if [ -f "$ENV_FILE" ]; then
        step "Using existing $ENV_FILE (left untouched)"
    else
        step "Creating $ENV_FILE with fresh random values"
        INVITE=$(printf 'dgx-%s' "$(gen_hex 6)")
        BASE_URL="${DGX_BASE_URL:-http://host.docker.internal:8041/v1}"
        DS_KEY="${DEEPSEEK_API_KEY:-}"
        cat > "$ENV_FILE" <<EOF
# Generated by scripts/quickstart.sh on $(date -u '+%Y-%m-%dT%H:%M:%SZ').
# Git-ignored. Edit it, then re-run the script (or 'docker compose up -d').
# Every key is documented in server/.env.example.

# --- where the server listens ---------------------------------------------
DGXCHAT_HOST=0.0.0.0
DGXCHAT_PORT=$PORT
DGXCHAT_DATA_DIR=/data
WEB_DIR=/app/web

# --- your model gateway (OpenAI compatible) --------------------------------
# MUST be reachable from inside the container: a LAN address, not 127.0.0.1.
DGX_BASE_URL=$BASE_URL
DGX_API_KEY=
DGX_MODEL_MAP={"deepseek-flash":"your-model","deepseek-v4-pro":"your-model"}

# --- accounts --------------------------------------------------------------
# The first account to register becomes the administrator.
REGISTRATION_MODE=invite
# Shared invite code generated for you; per-user codes live in /admin.
DGXCHAT_INVITE_CODE=$INVITE
TOKEN_TTL_DAYS=0

# --- optional: web search, TTS and ASR (never used for chat text) ----------
DEEPSEEK_API_KEY=$DS_KEY
DEEPSEEK_BASE_URL=https://api.deepseek.com
SEARCH_MODE=dgx
TTS_PROVIDER=deepseek
ASR_PROVIDER=deepseek

# --- abuse control ---------------------------------------------------------
LOGIN_MAX_FAILURES=10
LOGIN_WINDOW_SECONDS=300
REGISTER_MAX_PER_HOUR=5
MESSAGE_RATE_PER_MINUTE=20
DAILY_TOKEN_QUOTA=0
DAILY_TTS_CHARS=20000
DGXCHAT_DOCS=0
EOF
        chmod 600 "$ENV_FILE" 2>/dev/null || true
        say "    wrote $ENV_FILE (mode 600)"
        say "    generated invite code: $INVITE"
        NEW_ENV=1
    fi
fi

# --- 3. web UI ---------------------------------------------------------------
if [ "$STATUS_ONLY" -eq 0 ]; then
    # Publish a fresh UI whenever the sources are newer than what is in web/, so
    # that `git pull && ./scripts/quickstart.sh` upgrades the front end too
    # instead of leaving a new backend talking to an old bundle.
    NEED_BUILD=0
    if [ -n "$REBUILD_WEB" ] && [ "$REBUILD_WEB" -eq 1 ]; then
        NEED_BUILD=1
    elif [ ! -f "web/index.html" ]; then
        NEED_BUILD=1
    elif [ -d "app/src" ] && [ -n "$(find app/src app/package.json app/rspack.config.ts \
            -newer web/index.html -print -quit 2>/dev/null)" ]; then
        NEED_BUILD=1
    fi

    if [ "$NEED_BUILD" -eq 0 ]; then
        step "Web UI already up to date in web/"
    elif [ "$API_ONLY" -eq 0 ] && command -v pnpm >/dev/null 2>&1; then
        step "Building the web UI (pnpm)"
        ( cd app && pnpm install --frozen-lockfile && pnpm build ) \
            || die "the web UI failed to build; see the output above."
        mkdir -p web && cp -R app/dist/. web/
    elif [ -f "app/dist/index.html" ]; then
        # No pnpm: we can only publish what is already built. Say so, because a
        # stale bundle next to a new backend is how upgrades go wrong.
        step "Publishing the existing app/dist into web/ (pnpm not available)"
        warn "app/dist may be older than app/src; rebuild it elsewhere with
      'cd app && pnpm install && pnpm build' if anything looks stale."
        mkdir -p web && cp -R app/dist/. web/
    elif [ "$API_ONLY" -eq 1 ]; then
        mkdir -p web
    else
        warn "no pnpm and no app/dist — starting the API only.
      Build the UI elsewhere with 'cd app && pnpm install && pnpm build',
      then copy app/dist/* into ./web/ and re-run." >&2
        mkdir -p web
    fi
fi

if [ "$STATUS_ONLY" -eq 0 ]; then
    # --- 4. start -----------------------------------------------------------
    step "Building and starting the stack (this can take a few minutes)"
    docker compose -f "$COMPOSE_FILE" up -d --build
fi

# --- 5. wait for health ------------------------------------------------------
http_ok() {
    if command -v curl >/dev/null 2>&1; then
        curl -fsS -m 3 "$1" >/dev/null 2>&1
    elif command -v wget >/dev/null 2>&1; then
        wget -q -T 3 -O /dev/null "$1" >/dev/null 2>&1
    elif command -v python3 >/dev/null 2>&1; then
        python3 - "$1" <<'PY' >/dev/null 2>&1
import sys, urllib.request
urllib.request.urlopen(sys.argv[1], timeout=3).read()
PY
    else
        return 1
    fi
}

step "Waiting for http://127.0.0.1:$PORT/health"
i=0
HEALTHY=0
while [ "$i" -lt 90 ]; do
    if http_ok "http://127.0.0.1:$PORT/health"; then HEALTHY=1; break; fi
    i=$((i + 1))
    sleep 2
done

if [ "$HEALTHY" -ne 1 ]; then
    warn "the service did not answer /health within 180s. Recent logs:"
    docker compose -f "$COMPOSE_FILE" logs --tail=60 || true
    die "startup did not complete — fix the configuration in $ENV_FILE and re-run."
fi

# --- 6. summary --------------------------------------------------------------
say ""
say "  DGX Chat is up."
say ""
say "    URL            http://localhost:$PORT/"
say "    Admin page     http://localhost:$PORT/admin"
say "    Health         http://localhost:$PORT/health"
say ""
say "  First steps"
say "    1. Open the URL above and register."
say "       The FIRST account on an empty database becomes the administrator."
say "    2. Open /admin to create users, invite codes and see usage."
say "    3. Edit $ENV_FILE, then 'docker compose -f $COMPOSE_FILE up -d' to apply."
say ""
say "  Logs"
say "    docker compose -f $COMPOSE_FILE logs -f"
say ""

if [ "${NEW_ENV:-0}" -eq 1 ]; then
    warn "DGX_BASE_URL is still the placeholder in $ENV_FILE."
    warn "Set it to YOUR OpenAI-compatible gateway (reachable from inside the"
    warn "container) and map your models in DGX_MODEL_MAP, then restart."
fi
