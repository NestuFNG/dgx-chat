<#
.SYNOPSIS
  DGX Chat — one-command deployment (Windows PowerShell 7+).

.DESCRIPTION
  Builds and starts the Docker stack, creates .env with fresh random values if
  it is missing, waits for /health and prints what to do next. Re-running is
  safe: an existing .env and the data volume are never overwritten.

  Requirements: Docker Desktop (or Docker Engine) with the compose plugin.

.EXAMPLE
  pwsh ./scripts/quickstart.ps1
  pwsh ./scripts/quickstart.ps1 -ApiOnly
  pwsh ./scripts/quickstart.ps1 -Status
#>
[CmdletBinding()]
param(
    [switch]$ApiOnly,
    [switch]$Status
)

$ErrorActionPreference = "Stop"

$RepoDir    = Split-Path -Parent $PSScriptRoot
$ComposeFile = Join-Path $RepoDir "server\docker-compose.yml"
$EnvFile    = Join-Path $RepoDir "server\.env"
$WebDir     = Join-Path $RepoDir "web"
$DistDir    = Join-Path $RepoDir "app\dist"
$Port       = "8439"   # published port from server/docker-compose.yml

function Step([string]$Text) { Write-Host "`n==> $Text" -ForegroundColor Cyan }
function Die([string]$Text)  { Write-Host "error: $Text" -ForegroundColor Red; exit 1 }

# --- 1. prerequisites --------------------------------------------------------
Step "Checking docker"
if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    Die "docker is not installed. Install Docker Desktop, then re-run this script."
}
docker compose version *> $null
if ($LASTEXITCODE -ne 0) {
    Die "the 'docker compose' plugin is missing. Update Docker Desktop / install docker-compose-plugin."
}
if (-not (Test-Path $ComposeFile)) {
    Die "missing $ComposeFile — run this script from a clone of the repository."
}

# --- 2. .env -----------------------------------------------------------------
function New-Hex([int]$Bytes) {
    $buf = New-Object byte[] $Bytes
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($buf)
    ($buf | ForEach-Object { $_.ToString("x2") }) -join ""
}

$NewEnv = $false
if (-not $Status) {
    if (Test-Path $EnvFile) {
        Step "Using existing server\.env (left untouched)"
    } else {
        Step "Creating server\.env with fresh random values"
        $invite  = "dgx-" + (New-Hex 6)
        $baseUrl = if ($env:DGX_BASE_URL) { $env:DGX_BASE_URL } else { "http://host.docker.internal:8041/v1" }
        $dsKey   = if ($env:DEEPSEEK_API_KEY) { $env:DEEPSEEK_API_KEY } else { "" }
        $stamp   = (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ssZ")
        $lines = @(
            "# Generated by scripts/quickstart.ps1 on $stamp.",
            "# Git-ignored. Edit it, then re-run the script (or 'docker compose up -d').",
            "# Every key is documented in server/.env.example.",
            "",
            "# --- where the server listens ---------------------------------------------",
            "DGXCHAT_HOST=0.0.0.0",
            "DGXCHAT_PORT=$Port",
            "DGXCHAT_DATA_DIR=/data",
            "WEB_DIR=/app/web",
            "",
            "# --- your model gateway (OpenAI compatible) --------------------------------",
            "# MUST be reachable from inside the container: a LAN address, not 127.0.0.1.",
            "DGX_BASE_URL=$baseUrl",
            "DGX_API_KEY=",
            'DGX_MODEL_MAP={"deepseek-flash":"your-model","deepseek-v4-pro":"your-model"}',
            "",
            "# --- accounts --------------------------------------------------------------",
            "# The first account to register becomes the administrator.",
            "REGISTRATION_MODE=invite",
            "# Shared invite code generated for you; per-user codes live in /admin.",
            "DGXCHAT_INVITE_CODE=$invite",
            "TOKEN_TTL_DAYS=0",
            "",
            "# --- optional: web search, TTS and ASR (never used for chat text) ----------",
            "DEEPSEEK_API_KEY=$dsKey",
            "DEEPSEEK_BASE_URL=https://api.deepseek.com",
            "SEARCH_MODE=dgx",
            "TTS_PROVIDER=deepseek",
            "ASR_PROVIDER=deepseek",
            "",
            "# --- abuse control ---------------------------------------------------------",
            "LOGIN_MAX_FAILURES=10",
            "LOGIN_WINDOW_SECONDS=300",
            "REGISTER_MAX_PER_HOUR=5",
            "MESSAGE_RATE_PER_MINUTE=20",
            "DAILY_TOKEN_QUOTA=0",
            "DAILY_TTS_CHARS=20000",
            "DGXCHAT_DOCS=0"
        )
        [System.IO.File]::WriteAllLines($EnvFile, $lines, (New-Object System.Text.UTF8Encoding($false)))
        Write-Host "    wrote server\.env"
        Write-Host "    generated invite code: $invite"
        $NewEnv = $true
    }
}

# --- 3. web UI ---------------------------------------------------------------
if (-not $Status) {
    if (Test-Path (Join-Path $WebDir "index.html")) {
        Step "Web UI already present in web\"
    } elseif (Test-Path (Join-Path $DistDir "index.html")) {
        Step "Publishing app\dist into web\"
        New-Item -ItemType Directory -Force -Path $WebDir | Out-Null
        Copy-Item -Path (Join-Path $DistDir "*") -Destination $WebDir -Recurse -Force
    } elseif (-not $ApiOnly -and (Get-Command pnpm -ErrorAction SilentlyContinue)) {
        Step "Building the web UI (pnpm)"
        Push-Location (Join-Path $RepoDir "app")
        try {
            pnpm install --frozen-lockfile
            if ($LASTEXITCODE -ne 0) { throw "pnpm install failed" }
            pnpm build
            if ($LASTEXITCODE -ne 0) { throw "pnpm build failed" }
        } finally { Pop-Location }
        New-Item -ItemType Directory -Force -Path $WebDir | Out-Null
        Copy-Item -Path (Join-Path $DistDir "*") -Destination $WebDir -Recurse -Force
    } else {
        New-Item -ItemType Directory -Force -Path $WebDir | Out-Null
        Write-Warning "no web\index.html, no app\dist and no pnpm — starting the API only.
      Build the UI with 'cd app; pnpm install; pnpm build', copy app\dist\* into .\web\
      and re-run this script."
    }
}

# --- 4. start ----------------------------------------------------------------
if (-not $Status) {
    Step "Building and starting the stack (this can take a few minutes)"
    docker compose -f $ComposeFile up -d --build
    if ($LASTEXITCODE -ne 0) { Die "docker compose up failed." }
}

# --- 5. wait for health ------------------------------------------------------
Step "Waiting for http://127.0.0.1:$Port/health"
$healthy = $false
for ($i = 0; $i -lt 90; $i++) {
    try {
        $r = Invoke-WebRequest -Uri "http://127.0.0.1:$Port/health" -TimeoutSec 3 -UseBasicParsing
        if ($r.StatusCode -eq 200) { $healthy = $true; break }
    } catch { Start-Sleep -Seconds 2 }
}

if (-not $healthy) {
    Write-Warning "the service did not answer /health within 180s. Recent logs:"
    docker compose -f $ComposeFile logs --tail=60
    Die "startup did not complete — fix the configuration in server\.env and re-run."
}

# --- 6. summary --------------------------------------------------------------
Write-Host ""
Write-Host "  DGX Chat is up." -ForegroundColor Green
Write-Host ""
Write-Host "    URL            http://localhost:$Port/"
Write-Host "    Admin page     http://localhost:$Port/admin"
Write-Host "    Health         http://localhost:$Port/health"
Write-Host ""
Write-Host "  First steps"
Write-Host "    1. Open the URL above and register."
Write-Host "       The FIRST account on an empty database becomes the administrator."
Write-Host "    2. Open /admin to create users, invite codes and see usage."
Write-Host "    3. Edit server\.env, then 'docker compose -f server\docker-compose.yml up -d'."
Write-Host ""
Write-Host "  Logs"
Write-Host "    docker compose -f server\docker-compose.yml logs -f"
Write-Host ""

if ($NewEnv) {
    Write-Warning "DGX_BASE_URL is still the placeholder in server\.env.
      Set it to YOUR OpenAI-compatible gateway (reachable from inside the
      container) and map your models in DGX_MODEL_MAP, then restart."
}
