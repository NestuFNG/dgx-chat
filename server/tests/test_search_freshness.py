"""Retrieval requests must carry the server's current date (freshness bug).

Without a temporal anchor the official model guesses "now" and searches for
months-old news; these tests freeze the clock.
"""

from __future__ import annotations

import logging
from datetime import datetime, timedelta, timezone

import pytest

import app.search as search_module
from app.search import (
    SearchService,
    build_retrieval_payload,
    format_utc_offset,
    retrieval_time_context,
)

FROZEN = datetime(2026, 11, 17, 15, 44, tzinfo=timezone(timedelta(hours=8)))


def test_time_context_contains_local_date_and_offset():
    text = retrieval_time_context(FROZEN)
    assert "2026年11月17日" in text
    assert "15:44" in text
    assert "UTC+08:00" in text
    assert "2026-11-17" in text
    assert "最近" in text and "日期" in text


def test_time_context_handles_naive_and_negative_offsets():
    naive = datetime(2026, 1, 2, 3, 4)
    text = retrieval_time_context(naive)  # must not raise, gets local tz
    assert "2026年1月2日" in text
    assert "2026-01-02" in text

    west = datetime(2026, 7, 1, 9, 0, tzinfo=timezone(timedelta(hours=-5)))
    assert format_utc_offset(west) == "UTC-05:00"
    assert "UTC-05:00" in retrieval_time_context(west)


def test_retrieval_payload_has_system_date_and_original_query():
    payload = build_retrieval_payload("最近有什么重要的人工智能新闻？", model="deepseek-flash", now=FROZEN)
    assert payload["system"] == retrieval_time_context(FROZEN)
    assert payload["messages"] == [{"role": "user", "content": "最近有什么重要的人工智能新闻？"}]
    assert payload["thinking"] == {"type": "disabled"}
    assert payload["tools"] == [{"type": "deepseek_web_search", "name": "deepseek_web_search"}]
    assert payload["stream"] is True


@pytest.mark.asyncio
async def test_official_retrieval_sends_frozen_date_and_logs_queries(settings, monkeypatch, caplog):
    monkeypatch.setattr(search_module, "_now_local", lambda: FROZEN)
    settings.search.mode = "dgx"
    settings.search.official_api_key = "sk-test"
    captured: dict = {}

    class FakeUpstream:
        def iter_events(self, payload, api_key):
            captured["payload"] = payload
            captured["api_key"] = api_key

            async def gen():
                yield "content_block_start", {
                    "type": "content_block_start",
                    "index": 0,
                    "content_block": {
                        "type": "server_tool_use",
                        "id": "srvtoolu_s_00_" + "a" * 32,
                        "name": "deepseek_web_search",
                        "input": {"action": "search", "queries": ["2026年11月17日AI新闻"]},
                        "caller": {"type": "direct"},
                        "kind": "search",
                    },
                }
                yield "content_block_start", {
                    "type": "content_block_start",
                    "index": 1,
                    "content_block": {
                        "type": "web_search_tool_result",
                        "tool_use_id": "srvtoolu_s_00_" + "a" * 32,
                        "kind": "search",
                        "content": [
                            {
                                "type": "web_search_result",
                                "title": "今天的新闻",
                                "url": "https://example.com/today",
                                "encrypted_content": "",
                                "page_age": "2026-11-17T08:00:00+00:00",
                                "snippet": "今天的",
                                "site_name": "example",
                                "site_icon": None,
                            }
                        ],
                    },
                }

            return gen()

    service = SearchService.__new__(SearchService)
    service.settings = settings
    service.upstream = FakeUpstream()

    with caplog.at_level(logging.INFO, logger="dgxchat.search"):
        plan = await service.plan(
            query="最近有什么重要的人工智能新闻？",
            urls=[],
            want_search=True,
            want_read_url=False,
            official_api_key="sk-test",
        )
    payload = captured["payload"]
    assert "2026年11月17日" in payload["system"]
    assert "2026-11-17" in payload["system"]
    assert payload["messages"][0]["content"] == "最近有什么重要的人工智能新闻？"
    assert plan.sources and plan.sources[0].page_age == "2026-11-17T08:00:00+00:00"
    log_text = "\n".join(record.getMessage() for record in caplog.records)
    assert "search queries generated by official model" in log_text
    assert "2026年11月17日AI新闻" in log_text
