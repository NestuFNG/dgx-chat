def site_icon_for(url: str) -> str | None:
    host = urlparse(url).hostname or ""
    if not host:
        return None
    return f"https://cdn.deepseek.com/site-icons/{host}"


def extract_urls(text: str, limit: int) -> list[str]:
    seen: list[str] = []
    for match in _URL_RE.finditer(text or ""):
        url = match.group(0).rstrip(".,;:!?")
        if url not in seen:
            seen.append(url)
        if len(seen) >= limit:
            break
    return seen


def html_to_text(raw: str) -> tuple[str, str | None, str | None]:
    """Return ``(text, title, published_at)`` from an HTML document."""
    title_match = _HTML_TITLE_RE.search(raw)
    title = html.unescape(title_match.group(1)).strip() if title_match else None
    date_match = _META_DATE_RE.search(raw)
    published = date_match.group(1).strip() if date_match else None
    body = _SCRIPT_RE.sub(" ", raw)
    body = _COMMENT_RE.sub(" ", body)
    body = re.sub(r"<(br|/p|/div|/li|/h[1-6]|/tr)\s*/?>", "\n", body, flags=re.IGNORECASE)
    body = _TAG_RE.sub(" ", body)
    body = html.unescape(body)
    body = body.replace("\r\n", "\n").replace("\r", "\n")
    body = _WS_RE.sub(" ", body)
    lines = [line.strip() for line in body.split("\n")]
    text = "\n".join(line for line in lines if line)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip(), title, published


def truncate(text: str, limit: int) -> str:
    if len(text) <= limit:
        return text
    return text[:limit].rstrip() + "…"


