def synth_search_blocks(
    queries: list[str], sources: list[Source], sequence: int = 0
) -> tuple[dict[str, Any], dict[str, Any]]:
    """Build spec-compliant ``server_tool_use`` + ``web_search_tool_result`` blocks."""
    tool_id = f"srvtoolu_s_{sequence:02d}_{secrets.token_hex(16)}"
    tool_block = {
        "type": "server_tool_use",
        "id": tool_id,
        "name": "deepseek_web_search",
        "input": {"action": "search", "queries": queries},
        "caller": {"type": "direct"},
        "kind": "search",
    }
    result_block = {
        "type": "web_search_tool_result",
        "tool_use_id": tool_id,
        "content": [source.to_block_item() for source in sources],
        "kind": "search",
    }
    return tool_block, result_block


