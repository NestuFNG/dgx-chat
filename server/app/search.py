@dataclass(slots=True)
class Source:
    title: str
    url: str
    snippet: str = ""
    site_name: str | None = None
    site_icon: str | None = None
    page_age: str | None = None
    encrypted_content: str = ""

    def to_block_item(self) -> dict[str, Any]:
        """One entry of ``web_search_tool_result.content`` (parseEvent-valid)."""
        return {
            "type": "web_search_result",
            "title": self.title or self.url,
            "url": self.url,
            "encrypted_content": self.encrypted_content or "",
            "page_age": self.page_age,
            "snippet": self.snippet or "",
            "site_name": self.site_name,
            "site_icon": self.site_icon,
        }


@dataclass(slots=True)
class FetchedPage:
    url: str
    title: str | None = None
    text: str = ""
    published_at: str | None = None
    error: str | None = None


@dataclass(slots=True)
class SearchPlan:
    """Everything the compat layer needs to serve one turn's retrieval."""

    blocks: list[dict[str, Any]] = field(default_factory=list)
    context_text: str = ""
    sources: list[Source] = field(default_factory=list)
    pages: list[FetchedPage] = field(default_factory=list)
    notice: str = "off"
    web_search_requests: int = 0
    web_fetch_requests: int = 0


